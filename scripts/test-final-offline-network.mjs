import assert from "node:assert/strict"
import { readFileSync } from "node:fs"

const read = (file) => readFileSync(new URL(`../${file}`, import.meta.url), "utf8")
const dashboard = read("app/dashboard/page.tsx")
const layout = read("app/dashboard/layout.tsx")
const updatePanel = read("components/AppUpdatesPanel.tsx")
const updateBanner = read("components/AppUpdateBanner.tsx")
const updatePrompt = read("components/AppUpdatePrompt.tsx")
const updateCoordinator = read("components/desktop/DesktopUpdateCoordinator.tsx")
const updateState = read("lib/desktop/update-state.ts")
const rootLayout = read("app/layout.tsx")
const offlineBar = read("components/offline/OfflineStatusBar.tsx")
const authBridge = read("components/desktop/DesktopAuthBridge.tsx")
const apiBridge = read("components/desktop/DesktopApiBridge.tsx")
const clientFetch = read("lib/api/client-fetch.ts")
const updates = read("lib/app-updates.ts")
const invoicePage = read("app/dashboard/invoices/page.tsx")
const repositories = read("lib/offline/local/repositories.ts")
const offlineDb = read("lib/offline/db.ts")
const loginPage = read("app/login/page.tsx")
const licensePage = read("app/offline/page.tsx")

assert.doesNotMatch(dashboard, /AppUpdateBanner/, "The dashboard must not mount an application update banner.")
assert.doesNotMatch(layout, /OfflineStatusBar/, "The desktop layout must not mount sync/update queue status.")
assert.doesNotMatch(layout, /prepareOfflineWorkspace\(restoredWorkspace/, "A restored licensed desktop workspace must not start cloud preparation.")
assert.match(rootLayout, /DesktopUpdateCoordinator/, "Packaged users must receive genuine update notifications from the root lifecycle.")
assert.match(updateCoordinator, /!navigator\.onLine/, "Explicit update checks must remain inert while fully offline.")
assert.match(updateCoordinator, /setInterval\(handleCheck, UPDATE_CHECK_INTERVAL_MS\)/, "Online update checks must use a bounded periodic schedule.")
assert.match(updateCoordinator, /setTimeout\(handleCheck, STARTUP_CHECK_DELAY_MS\)/, "The desktop must check for updates after startup.")
assert.match(updateCoordinator, /addEventListener\("online", handleOnline\)/, "The update service must retry after network restoration.")
assert.match(updateCoordinator, /addEventListener\(UPDATE_CHECK_EVENT, handleCheck\)/, "The update service must also remain available through a user-triggered check.")
assert.match(updateCoordinator, /updateIsUnsafe/, "Automatic updates must wait while billing or unsaved work is active.")
assert.match(updateCoordinator, /Bezgrow \{latestVersion\} is available/, "The desktop notification must name the available Bezgrow version.")
assert.match(updateCoordinator, />Update Now<\//, "The desktop notification must expose Update Now.")
assert.match(updateCoordinator, />Later<\//, "The desktop notification must expose Later without permanently dismissing the release.")
assert.match(updateState, /48 \* 60 \* 60 \* 1000/, "The first safe automatic update opportunity must start after 48 hours.")
assert.match(updatePanel, /onClick=\{\(\) => void checkUpdates\(\)\}/, "Settings must expose the manual update action.")
assert.match(updatePanel, /Connect to the internet to check for updates\./, "Offline update checks need calm wording.")
assert.match(updateBanner, /return null/, "The former dashboard update banner must stay disabled.")
assert.match(updatePrompt, /return null/, "Automatic update prompts must stay disabled.")
assert.match(offlineBar, /return null/, "The former pending-sync banner must stay disabled.")
assert.doesNotMatch(authBridge, /supabase|restoreDesktopSession|getSession/, "Desktop startup must not restore a cloud session.")
assert.match(apiBridge, /not implemented in the local SQLite repository/, "Unimplemented desktop API routes must not silently call the cloud.")
assert.match(apiBridge, /REMOTE_SETUP_PATHS/, "Only explicit initial setup/auth endpoints may use the desktop proxy.")
assert.match(clientFetch, /if \(await isTauriRuntimeAsync\(\)\)[\s\S]*not implemented in the local SQLite repository/, "Desktop client fetch must block cloud fallback.")
assert.equal((updates.match(/readManifest\(/g) || []).length, 2, "The update helper should make one manifest request per check.")
assert.doesNotMatch(invoicePage, /Pending Update/, "Invoice queue state must not be presented as an app update.")
assert.match(repositories, /INSERT OR IGNORE INTO organizations/, "Repository readiness checks must not overwrite an existing business.")
assert.match(repositories, /Object\.hasOwn\(input, "logo_path"\)/, "Partial workspace records must preserve managed logo metadata.")
assert.match(offlineDb, /if \(currentOrganization\)/, "Desktop workspace caching must merge authoritative local business settings and stable metadata.")
assert.match(offlineDb, /isPlaceholder && payload\.organization\?\.name/, "A placeholder local organization must not replace the licensed business name.")
assert.match(loginPage, /\/offline\?reason=logged_out/, "An explicitly logged-out desktop must open the local licence lifecycle, not cloud login.")
assert.match(licensePage, /Continue \/ Open Dashboard/, "The licence screen must reopen through its verified stored licence without internet.")
assert.match(licensePage, /localLicenseSnapshot/, "Offline continuation must re-verify the stored licence before clearing the logout marker.")

console.log("final-offline-network-contract-ok")
