import assert from "node:assert/strict"
import { readFileSync } from "node:fs"

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8")

const engine = read("components/print/PrintEngine.tsx")
const pdfClient = read("lib/invoice-pdf-client.ts")
const pdfGenerator = read("lib/pdf-invoice.ts")
const builder = read("lib/print-invoice-builder.ts")
const printPage = read("app/dashboard/invoices/[id]/print/page.tsx")
const blocks = read("components/print/templates/PrintBlocks.tsx")
const thermal = read("components/print/templates/ThermalTemplate.tsx")
const rust = read("src-tauri/src/lib.rs")

assert.doesNotMatch(engine, /publicPdfUrl|\/public\/invoices/, "Invoice actions must not depend on the online public PDF route.")
assert.match(engine, /saveInvoicePdf\(effectiveInvoice\)/, "Save PDF must generate from the locally loaded invoice.")
assert.match(engine, /downloadInvoicePdf\(effectiveInvoice\)/, "Download PDF must generate from the locally loaded invoice.")
assert.match(engine, /shareInvoicePdf\(effectiveInvoice\)/, "Share PDF must use an actual local PDF file.")
assert.match(engine, /if \(!navigator\.onLine\)/, "WhatsApp must preserve the PDF and explain the offline requirement.")
assert.match(engine, /printFromHiddenFrame\(html\)/, "Printing must use an embedded document instead of a popup-only path.")

assert.match(pdfClient, /createInvoicePdf\(invoice\)/, "Client PDF actions must use the in-memory invoice generator.")
assert.match(pdfClient, /new File\(\[createInvoicePdfBlob\(invoice\)\]/, "Native sharing must receive a PDF file.")
assert.match(pdfClient, /desktop_save_invoice_pdf/, "Packaged desktop PDF saving must cross the native file boundary.")
assert.doesNotMatch(pdfGenerator, /\bBuffer\b/, "The invoice PDF generator must remain browser-safe.")
assert.match(pdfGenerator, /Thank you for your business\..*Generated by Bezgrow/, "Generated PDFs need the professional Bezgrow footer.")
assert.match(pdfGenerator, /brandInitial/, "Generated PDFs must show the business identity even without an uploaded logo.")

assert.match(builder, /resolvePrintOrganization/, "Invoice branding must resolve the best cached business record.")
assert.doesNotMatch(builder, /\/brand\/bezgrow-logo-3d\.png/, "A missing business logo must never be replaced by the Bezgrow product logo.")
assert.match(builder, /logoUrl: stringFrom\(organization/, "The invoice must use only the business's own uploaded logo.")
assert.match(printPage, /cachedSettings\.organization/, "Offline print branding must read locally saved business settings.")
assert.match(printPage, /cachedWorkspace\?\.organization/, "Offline print branding must use the licensed workspace identity.")

assert.match(blocks, /Thank you for your business\./, "A4 invoices need a thank-you footer.")
assert.match(blocks, /Generated by Bezgrow/, "A4 invoices need the Bezgrow attribution.")
assert.match(thermal, /BusinessLogo/, "Thermal invoices must show the business logo or monogram.")
assert.match(thermal, /invoice\.notes &&/, "Thermal invoices must avoid duplicate fallback thank-you text.")

assert.match(rust, /fn desktop_save_invoice_pdf/, "Desktop must expose a native offline PDF save command.")
assert.match(rust, /bytes\.starts_with\(b"%PDF-"\)/, "Desktop must reject invalid PDF bytes.")
assert.match(rust, /download_dir\(\)[\s\S]*Bezgrow Invoices/, "Desktop invoices must save to a predictable Downloads folder.")
assert.match(rust, /desktop_save_invoice_pdf,[\s\S]*open_external_url/, "The native PDF command must be registered.")

console.log("invoice-print-contract-ok")
